/**
 * URBANO Gaming Competitions — return-to-intent pure logic (UG-CR-
 * GATE-031, revised under UG-CR-GATE-081 Phase 3A). Deliberately
 * factored out of competitions.html's own inline script so it can be
 * unit-tested directly (public/*.html pages have no bundler/import
 * support and are never otherwise importable by a test — see
 * urbanoAuth.js's own header comment) rather than duplicated as two
 * silently-driftable copies. Every function here is pure: no `window`,
 * no fetch, no mutation, no browser storage. The one caller,
 * competitions.html, supplies the real `location.href`/`location.search`
 * strings in and applies the returned string via `history.replaceState`
 * itself — the thinnest possible DOM-touching wrapper around logic that
 * is otherwise plain string/regex validation.
 *
 * Loaded as a plain classic (non-module) script — this project's own
 * package.json sets "type": "module", which makes a CommonJS
 * module.exports branch here resolve inconsistently under Node/Vite's
 * require() interop; __tests__/competitionsIntent.test.ts instead
 * executes this exact file's source text directly (the same thing the
 * browser does), reading the result off `globalThis.CompetitionsIntent`
 * — this IIFE's own fallback when `window` is undefined.
 *
 * UG-CR-GATE-081 Phase 3A revision: the navigation intent this
 * capability carries is no longer a raw competitionId/teamId uuid —
 * those are exactly the internal primary keys GATE-081 requires never
 * appear in a user-visible URL. The query parameters are now `c`
 * (competition public_code) and `t` (team public_code), opaque
 * non-identifying tokens generated by lib/gaming/competitions/
 * publicCode.ts (16 random bytes, base64url, 22 characters, charset
 * [A-Za-z0-9_-]). The accepted allowlist is correspondingly a shape
 * check on that exact format — never a UUID pattern — but the
 * no-authority guarantee is unchanged: possession of a public_code is a
 * navigation hint only, never a grant of membership, captaincy, or
 * approval. Every actual authorization decision is still re-verified
 * server-side by whichever route this intent eventually leads to, via
 * the resolve endpoint turning a code back into the real id the
 * existing routes expect.
 */
(function (root) {
  // 16 bytes of crypto.randomBytes, base64url-encoded with no padding —
  // exactly 22 characters from [A-Za-z0-9_-]. See
  // lib/gaming/competitions/publicCode.ts for the generator this shape
  // must match.
  var PUBLIC_CODE_PATTERN = /^[A-Za-z0-9_-]{22}$/;

  /** Strict allowlist check: true only for a syntactically valid opaque public_code string. Anything else (undefined, null, empty, a UUID, a URL, a script/protocol string, a path, an overlong string) is rejected. */
  function isValidCompetitionCode(value) {
    return typeof value === "string" && PUBLIC_CODE_PATTERN.test(value);
  }

  /** Same shape as isValidCompetitionCode — a distinct name only for readability at call sites; the validation rule (any syntactically valid public_code) is identical. */
  function isValidTeamCode(value) {
    return typeof value === "string" && PUBLIC_CODE_PATTERN.test(value);
  }

  /**
   * Extracts and validates the competition-code intent from a URL's own
   * query string (e.g. `location.search`, `"?c=...&x=1"`). Returns the
   * validated code, or null for anything missing, malformed, or of the
   * wrong shape — there is no partial-trust outcome.
   */
  function getIntentCompetitionCodeFromSearch(search) {
    var raw;
    try {
      raw = new URLSearchParams(search || "").get("c");
    } catch (err) {
      return null;
    }
    return isValidCompetitionCode(raw) ? raw : null;
  }

  /** Same extraction/validation, for the `t` (team public_code) query parameter. */
  function getIntentTeamCodeFromSearch(search) {
    var raw;
    try {
      raw = new URLSearchParams(search || "").get("t");
    } catch (err) {
      return null;
    }
    return isValidTeamCode(raw) ? raw : null;
  }

  /**
   * Reflects a server-CONFIRMED (competition public_code, team
   * public_code) pair together — an opened invitation always carries
   * both, so both are set (or left unchanged if already current) in one
   * history entry rather than two. teamCode is optional: passing
   * null/invalid clears it while still setting competitionCode, for the
   * ordinary (non-invitation) detail view.
   */
  function computeUrlWithIntent(currentHref, competitionCode, teamCode) {
    if (!isValidCompetitionCode(competitionCode)) return null;
    var url;
    try {
      url = new URL(currentHref);
    } catch (err) {
      return null;
    }
    var changed = false;
    if (url.searchParams.get("c") !== competitionCode) {
      url.searchParams.set("c", competitionCode);
      changed = true;
    }
    if (isValidTeamCode(teamCode)) {
      if (url.searchParams.get("t") !== teamCode) {
        url.searchParams.set("t", teamCode);
        changed = true;
      }
    } else if (url.searchParams.has("t")) {
      url.searchParams.delete("t");
      changed = true;
    }
    return changed ? url.pathname + url.search : null;
  }

  /** Strips both competition and team code intent from the URL. Returns null if there was nothing to remove. */
  function computeUrlWithoutIntent(currentHref) {
    var url;
    try {
      url = new URL(currentHref);
    } catch (err) {
      return null;
    }
    var changed = false;
    if (url.searchParams.has("c")) { url.searchParams.delete("c"); changed = true; }
    if (url.searchParams.has("t")) { url.searchParams.delete("t"); changed = true; }
    return changed ? url.pathname + url.search : null;
  }

  root.CompetitionsIntent = {
    isValidCompetitionCode: isValidCompetitionCode,
    isValidTeamCode: isValidTeamCode,
    getIntentCompetitionCodeFromSearch: getIntentCompetitionCodeFromSearch,
    getIntentTeamCodeFromSearch: getIntentTeamCodeFromSearch,
    computeUrlWithIntent: computeUrlWithIntent,
    computeUrlWithoutIntent: computeUrlWithoutIntent,
  };
})(typeof window !== "undefined" ? window : globalThis);
